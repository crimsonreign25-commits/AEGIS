import assert from 'node:assert/strict';
import { webcrypto } from 'node:crypto';
import {createSecureShare,openSecureShare,serializeSecureShare,parseSecureShare} from './secure-share.mjs';
const bytes=new TextEncoder().encode('AEGIS confidential test document');
const file=new Blob([bytes],{type:'text/plain'}); file.name='confidential.txt';
const pkg=await createSecureShare(file,{allowedMode:'both',expiresAt:null},'correct horse battery staple');
assert.equal(pkg.format,'AEGIS-SECURE-SHARE');
assert.equal(pkg.ciphertext.includes('AEGIS confidential'),false);
await assert.rejects(()=>openSecureShare(pkg,'wrong code','view'),/Incorrect security code/);
const viewed=await openSecureShare(pkg,'correct horse battery staple','view');
assert.equal(viewed.name,'confidential.txt');
assert.deepEqual(new Uint8Array(await viewed.blob.arrayBuffer()),bytes);
const downloaded=await openSecureShare(pkg,'correct horse battery staple','download');
assert.deepEqual(new Uint8Array(await downloaded.blob.arrayBuffer()),bytes);
const viewOnly=await createSecureShare(file,{allowedMode:'view'},'correct horse battery staple');
await assert.rejects(()=>openSecureShare(viewOnly,'correct horse battery staple','download'),/did not allow/);
const tampered={...pkg,meta:{...pkg.meta,name:'tampered.txt'}};
await assert.rejects(()=>openSecureShare(tampered,'correct horse battery staple','view'),/authentication failed/);
const roundtrip=await parseSecureShare(new File([await serializeSecureShare(pkg)],'share.aegis'));
assert.equal(roundtrip.format,'AEGIS-SECURE-SHARE');
console.log('PASS: code-wrapped random file key, AES-GCM confidentiality/authentication, wrong-code rejection, sender mode restrictions, recipient view/download choices, and package round-trip.');
