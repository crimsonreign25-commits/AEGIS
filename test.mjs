import { readFile, access } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { webcrypto } from 'node:crypto';
const html = await readFile('index.html','utf8');
const js = await readFile('app.js','utf8');
const sw = await readFile('sw.js','utf8');
const manifest = JSON.parse(await readFile('manifest.webmanifest','utf8'));
assert.match(html, /manifest\.webmanifest/);
assert.match(html, /app\.js/);
assert.match(js, /generateKey\(\{name:'ECDSA', namedCurve:'P-256'\}, false/);
assert.match(js, /generateKey\(\{name:'ECDH', namedCurve:'P-256'\}, false/);
assert.match(js, /indexedDB\.open/);
assert.match(js, /AEGIS-\$\{/);
assert.match(sw, /addAll\(CORE\)/);
assert.equal(manifest.short_name, 'AEGIS');
await access('public/aegis-icon.svg');
const signing = await webcrypto.subtle.generateKey({name:'ECDSA',namedCurve:'P-256'}, false, ['sign','verify']);
const agreement = await webcrypto.subtle.generateKey({name:'ECDH',namedCurve:'P-256'}, false, ['deriveKey','deriveBits']);
assert.equal(signing.privateKey.extractable, false);
assert.equal(agreement.privateKey.extractable, false);
const publicKey = await webcrypto.subtle.exportKey('raw', signing.publicKey);
const digest = new Uint8Array(await webcrypto.subtle.digest('SHA-256', publicKey));
assert.equal(digest.length, 32);
const message = new TextEncoder().encode('AEGIS local identity proof test');
const signature = await webcrypto.subtle.sign({name:'ECDSA',hash:'SHA-256'}, signing.privateKey, message);
assert.equal(await webcrypto.subtle.verify({name:'ECDSA',hash:'SHA-256'}, signing.publicKey, signature, message), true);
console.log('PASS: PWA manifest, service worker, P-256 key generation, non-extractable private keys, public-key fingerprint and ECDSA sign/verify checks.');
